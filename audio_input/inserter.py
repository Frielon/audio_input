"""Put the dictated text where the cursor is, as if it had been typed.

``paste`` (default): the text is put on the clipboard, Cmd+V is sent to the
focused app and, half a second later, the previous clipboard contents are put
back (unless something else used the clipboard in the meantime).  This works in
every app and with any input method active (e.g. Pinyin), and long texts
appear at once.  The temporary clipboard item is marked transient, so
clipboard managers that follow the nspasteboard.org convention skip it.

``type``: the text is sent as keyboard events carrying the characters; the
clipboard is not touched, but some apps (and input methods) handle long
synthetic typing poorly.

Before inserting, the Accessibility API is asked for the character before the
cursor, so that a sentence dictated right after a word gets a space.  If
another app came to the front while the speech was being transcribed, the text
is only copied to the clipboard instead of being typed into the wrong place.
"""
from __future__ import annotations

import logging
import re
import threading
import time
from dataclasses import dataclass
from typing import Callable, Optional

from .grammar import FILLERS

log = logging.getLogger(__name__)

KEY_V = 9  # kVK_ANSI_V
RESTORE_DELAY = 0.5
TRANSIENT_TYPES = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")
_NO_SPACE_AFTER = set("([{<\"'“‘/-–—\n\t ")
_NO_SPACE_BEFORE = set(".,!?;:)]}'\"’”…")


@dataclass
class AppInfo:
    pid: int
    name: str
    bundle: str


def frontmost_app() -> Optional[AppInfo]:
    from AppKit import NSWorkspace

    app = NSWorkspace.sharedWorkspace().frontmostApplication()
    if app is None:
        return None
    return AppInfo(int(app.processIdentifier()), str(app.localizedName() or ""), str(app.bundleIdentifier() or ""))


_SENTENCE_END = re.compile(r"[.!?]+$")


def strip_fillers(text: str) -> str:
    """``Um, so I think, uh, we should go.`` -> ``So I think we should go.``"""
    out: list[str] = []
    capitalize = False
    for tok in text.split():
        if re.sub(r"[^\w']", "", tok).lower() in FILLERS:
            end = _SENTENCE_END.search(tok)
            if not out:
                capitalize = True
            elif end and not re.search(r"[.!?,;:]$", out[-1]):
                out[-1] += end.group()
            elif not end and out[-1].endswith(","):
                out[-1] = out[-1][:-1]
            continue
        if capitalize and tok[:1].islower():
            tok = tok[0].upper() + tok[1:]
        capitalize = False
        out.append(tok)
    return " ".join(out)


def needs_leading_space(before: Optional[str], text: str) -> bool:
    """A space between the character before the cursor and the dictated text?"""
    if not before or not text:
        return False
    return before[-1] not in _NO_SPACE_AFTER and not before[-1].isspace() and text[0] not in _NO_SPACE_BEFORE


def char_before_caret(timeout: float = 0.25) -> Optional[str]:
    """The character before the text cursor in the focused field; "" at its start; None when unknown."""
    try:
        import ApplicationServices as AS
        from CoreFoundation import CFRangeMake

        system = AS.AXUIElementCreateSystemWide()
        AS.AXUIElementSetMessagingTimeout(system, timeout)
        err, focused = AS.AXUIElementCopyAttributeValue(system, AS.kAXFocusedUIElementAttribute, None)
        if err or focused is None:
            return None
        err, rng = AS.AXUIElementCopyAttributeValue(focused, AS.kAXSelectedTextRangeAttribute, None)
        if err or rng is None:
            return None
        ok, cf_range = AS.AXValueGetValue(rng, AS.kAXValueCFRangeType, None)
        if not ok:
            return None
        loc = int(cf_range.location)
        if loc <= 0:
            return ""
        param = AS.AXValueCreate(AS.kAXValueCFRangeType, CFRangeMake(loc - 1, 1))
        err, s = AS.AXUIElementCopyParameterizedAttributeValue(
            focused, AS.kAXStringForRangeParameterizedAttribute, param, None)
        if not err and s:
            return str(s)[-1]
        err, value = AS.AXUIElementCopyAttributeValue(focused, AS.kAXValueAttribute, None)
        if not err and isinstance(value, str) and 0 < loc <= len(value):
            return value[loc - 1]
    except Exception:  # an app with an unusual accessibility tree: just don't add a space
        log.debug("char_before_caret failed", exc_info=True)
    return None


def _post_key(keycode: int, flags: int = 0, text: Optional[str] = None) -> None:
    import Quartz

    src = Quartz.CGEventSourceCreate(Quartz.kCGEventSourceStatePrivate)
    for down in (True, False):
        ev = Quartz.CGEventCreateKeyboardEvent(src, keycode, down)
        if text is not None:
            Quartz.CGEventKeyboardSetUnicodeString(ev, len(text.encode("utf-16-le")) // 2, text)
        Quartz.CGEventSetFlags(ev, flags)
        Quartz.CGEventPost(Quartz.kCGHIDEventTap, ev)


def utf16_chunks(text: str, size: int = 20) -> list[str]:
    """Pieces of at most ``size`` UTF-16 units (one keyboard event carries at most 20), never splitting a character."""
    chunks, cur, units = [], "", 0
    for ch in text:
        n = 2 if ord(ch) > 0xFFFF else 1
        if units + n > size:
            chunks.append(cur)
            cur, units = "", 0
        cur += ch
        units += n
    if cur:
        chunks.append(cur)
    return chunks


def type_text(text: str, delay: float = 0.004) -> None:
    for chunk in utf16_chunks(text):
        _post_key(0, 0, chunk)
        time.sleep(delay)


def paste_shortcut() -> None:
    import Quartz

    _post_key(KEY_V, Quartz.kCGEventFlagMaskCommand)


class Clipboard:
    """Save, replace and restore the contents of a pasteboard (the general one by default)."""

    def __init__(self, pasteboard=None):
        from AppKit import NSPasteboard

        self.pb = pasteboard or NSPasteboard.generalPasteboard()

    def snapshot(self) -> list[dict]:
        items = []
        for item in self.pb.pasteboardItems() or []:
            data = {}
            for t in item.types():
                d = item.dataForType_(t)
                if d is not None:
                    data[str(t)] = d
            if data:
                items.append(data)
        return items

    def put_text(self, text: str, transient: bool = True) -> int:
        from AppKit import NSPasteboardItem, NSPasteboardTypeString
        from Foundation import NSData

        self.pb.clearContents()
        item = NSPasteboardItem.alloc().init()
        item.setString_forType_(text, NSPasteboardTypeString)
        if transient:
            for t in TRANSIENT_TYPES:
                item.setData_forType_(NSData.data(), t)
        self.pb.writeObjects_([item])
        return int(self.pb.changeCount())

    def restore(self, items: list[dict]) -> None:
        from AppKit import NSPasteboardItem

        self.pb.clearContents()
        objs = []
        for data in items:
            item = NSPasteboardItem.alloc().init()
            for t, d in data.items():
                item.setData_forType_(d, t)
            objs.append(item)
        if objs:
            self.pb.writeObjects_(objs)

    def text(self) -> Optional[str]:
        from AppKit import NSPasteboardTypeString

        s = self.pb.stringForType_(NSPasteboardTypeString)
        return None if s is None else str(s)

    @property
    def change_count(self) -> int:
        return int(self.pb.changeCount())


class Inserter:
    """``insert(text, target_pid)`` -> what happened: pasted / typed / copied / off."""

    def __init__(self, method: str = "paste", restore_clipboard: bool = True, smart_spacing: bool = True,
                 on_main: Optional[Callable[[Callable], object]] = None, clipboard: Optional[Clipboard] = None):
        self.method = method
        self.restore_clipboard = restore_clipboard
        self.smart_spacing = smart_spacing
        self.on_main = on_main or (lambda fn: fn())  # AppKit calls are made on the main thread in the app
        self._clipboard = clipboard
        self._lock = threading.Lock()
        self._saved: Optional[list[dict]] = None  # the user's clipboard while ours is on it
        self._ours: Optional[int] = None          # change count of our temporary clipboard item
        self._timer: Optional[threading.Timer] = None

    @property
    def clipboard(self) -> Clipboard:
        if self._clipboard is None:
            self._clipboard = Clipboard()
        return self._clipboard

    def insert(self, text: str, target_pid: Optional[int] = None) -> str:
        if not text or self.method == "none":
            return "off"
        front = frontmost_app()
        if target_pid is not None and front is not None and front.pid != target_pid:
            self.copy(text)
            return "copied"
        if self.smart_spacing and needs_leading_space(char_before_caret(), text):
            text = " " + text
        if self.method == "type":
            type_text(text)
            return "typed"
        self._paste(text)
        return "pasted"

    def copy(self, text: str) -> None:
        """Leave the text on the clipboard (no restore)."""
        with self._lock:
            self._cancel_restore()
            self._saved = self._ours = None
            self.on_main(lambda: self.clipboard.put_text(text, transient=False))

    def _cancel_restore(self) -> None:
        if self._timer is not None:
            self._timer.cancel()
            self._timer = None

    def _paste(self, text: str) -> None:
        with self._lock:
            self._cancel_restore()
            cb = self.clipboard
            if self._saved is None or self._ours != cb.change_count:
                # our previous item is gone (or there is none): the clipboard holds the user's data
                self._saved = self.on_main(cb.snapshot) if self.restore_clipboard else None
            self._ours = self.on_main(lambda: cb.put_text(text))
            paste_shortcut()
            if self.restore_clipboard:
                self._timer = threading.Timer(RESTORE_DELAY, self._restore)
                self._timer.daemon = True
                self._timer.start()

    def _restore(self) -> None:
        with self._lock:
            saved, ours = self._saved, self._ours
            self._saved = self._ours = None
            self._timer = None
            if saved is None:
                return
            cb = self.clipboard
            if cb.change_count != ours:
                return  # the clipboard was used after our paste: leave it alone
            self.on_main(lambda: cb.restore(saved))

    def flush(self) -> None:
        """Restore the clipboard now (at exit)."""
        timer = self._timer
        if timer is not None:
            timer.cancel()
            self._restore()
